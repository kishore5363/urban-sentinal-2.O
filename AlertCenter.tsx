import React, { useState } from 'react';
import { 
  AlertTriangle, 
  Waves, 
  Disc, 
  Activity, 
  MapPin, 
  Clock, 
  BusFront, 
  CheckCircle2, 
  Eye, 
  Check, 
  Filter, 
  Download, 
  Bell, 
  ShieldAlert,
  Sparkles
} from 'lucide-react';
import { useSentinel } from '../context/SentinelContext';
import { AlertItem, HazardType } from '../types';

export const AlertCenter: React.FC = () => {
  const { 
    alerts, 
    viewHazardOnMap, 
    acknowledgeAlert, 
    resolveAlert,
    simulateNewHazardDetection
  } = useSentinel();

  const [filterStatus, setFilterStatus] = useState<string>('all');
  const [downloadSuccess, setDownloadSuccess] = useState(false);

  const filteredAlerts = alerts.filter(alert => {
    if (filterStatus === 'all') return true;
    if (filterStatus === 'unacknowledged') return alert.status === 'unacknowledged';
    if (filterStatus === 'critical') return alert.severity === 'critical';
    if (filterStatus === 'acknowledged') return alert.status === 'acknowledged';
    if (filterStatus === 'resolved') return alert.status === 'resolved';
    return true;
  });

  const getAlertSeverityStyles = (severity: AlertItem['severity'], status: AlertItem['status']) => {
    if (status === 'resolved') {
      return {
        cardBg: 'bg-slate-900/60 border-slate-800/80',
        badge: 'bg-emerald-500/15 text-emerald-400 border-emerald-500/30',
        iconColor: 'text-emerald-400',
        borderColor: 'border-l-4 border-l-emerald-500'
      };
    }
    switch (severity) {
      case 'critical':
        return {
          cardBg: 'bg-rose-950/20 border-rose-800/60',
          badge: 'bg-rose-500/20 text-rose-300 border-rose-500/40 animate-pulse',
          iconColor: 'text-rose-400',
          borderColor: 'border-l-4 border-l-rose-500'
        };
      case 'high':
        return {
          cardBg: 'bg-amber-950/20 border-amber-800/60',
          badge: 'bg-amber-500/20 text-amber-300 border-amber-500/40',
          iconColor: 'text-amber-400',
          borderColor: 'border-l-4 border-l-amber-500'
        };
      default:
        return {
          cardBg: 'bg-blue-950/20 border-blue-800/60',
          badge: 'bg-blue-500/20 text-blue-300 border-blue-500/40',
          iconColor: 'text-blue-400',
          borderColor: 'border-l-4 border-l-blue-500'
        };
    }
  };

  const handleExport = () => {
    const dataStr = "data:text/json;charset=utf-8," + encodeURIComponent(JSON.stringify(alerts, null, 2));
    const downloadAnchor = document.createElement('a');
    downloadAnchor.setAttribute("href", dataStr);
    downloadAnchor.setAttribute("download", `urban_sentinel_alerts_${Date.now()}.json`);
    document.body.appendChild(downloadAnchor);
    downloadAnchor.click();
    downloadAnchor.remove();
    setDownloadSuccess(true);
    setTimeout(() => setDownloadSuccess(false), 2500);
  };

  return (
    <div id="alert-center-section" className="p-4 sm:p-6 lg:p-8 space-y-6 max-w-7xl mx-auto">
      {/* Top Banner */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 bg-slate-900/90 border border-slate-800 p-4 rounded-2xl">
        <div className="flex items-center gap-3">
          <div className="p-2.5 rounded-xl bg-rose-500/20 text-rose-400 border border-rose-500/30">
            <ShieldAlert className="w-6 h-6" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h2 className="text-lg font-extrabold text-white">
                Municipal Road Hazard Alert Center
              </h2>
              <span className="text-xs font-mono px-2 py-0.5 rounded bg-rose-500/20 text-rose-300 border border-rose-500/30">
                {alerts.filter(a => a.status === 'unacknowledged').length} PENDING ACTION
              </span>
            </div>
            <p className="text-xs text-slate-400">
              Immediate automated notifications generated by onboard bus edge units
            </p>
          </div>
        </div>

        {/* Action Controls */}
        <div className="flex items-center gap-2">
          <button
            id="export-alerts-json-btn"
            onClick={handleExport}
            className="px-3.5 py-2 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 text-xs font-mono font-medium border border-slate-700 transition-colors flex items-center gap-1.5"
          >
            <Download className="w-3.5 h-3.5 text-cyan-400" />
            <span>{downloadSuccess ? 'Exported!' : 'Export JSON'}</span>
          </button>
          <button
            id="simulate-alert-trigger-btn"
            onClick={() => simulateNewHazardDetection('waterlogging')}
            className="px-3.5 py-2 rounded-xl bg-rose-600 hover:bg-rose-500 text-white text-xs font-bold transition-all shadow-lg shadow-rose-950 flex items-center gap-1.5"
          >
            <Sparkles className="w-3.5 h-3.5" />
            <span>Simulate Critical Alert</span>
          </button>
        </div>
      </div>

      {/* Filter Tabs */}
      <div className="flex items-center gap-2 overflow-x-auto pb-2 scrollbar-thin">
        {[
          { id: 'all', label: 'All Alerts', count: alerts.length },
          { id: 'unacknowledged', label: 'Unacknowledged', count: alerts.filter(a => a.status === 'unacknowledged').length },
          { id: 'critical', label: 'Critical Only', count: alerts.filter(a => a.severity === 'critical').length },
          { id: 'acknowledged', label: 'Acknowledged', count: alerts.filter(a => a.status === 'acknowledged').length },
          { id: 'resolved', label: 'Resolved', count: alerts.filter(a => a.status === 'resolved').length },
        ].map(tab => (
          <button
            key={tab.id}
            id={`alert-filter-${tab.id}`}
            onClick={() => setFilterStatus(tab.id)}
            className={`px-3.5 py-2 rounded-xl text-xs font-mono font-semibold shrink-0 transition-all flex items-center gap-2 border ${
              filterStatus === tab.id
                ? 'bg-slate-800 text-white border-cyan-500/50 shadow-sm'
                : 'bg-slate-900/60 text-slate-400 border-slate-800 hover:text-slate-200'
            }`}
          >
            <span>{tab.label}</span>
            <span className="text-[10px] px-1.5 py-0.5 rounded bg-slate-950 text-slate-300">
              {tab.count}
            </span>
          </button>
        ))}
      </div>

      {/* Alert Cards List */}
      <div className="space-y-3.5">
        {filteredAlerts.length === 0 ? (
          <div className="p-12 text-center rounded-2xl bg-slate-900/50 border border-slate-800 space-y-2">
            <CheckCircle2 className="w-10 h-10 text-emerald-400 mx-auto" />
            <h3 className="text-base font-bold text-white">No alerts found in this view</h3>
            <p className="text-xs text-slate-400">All notifications for this filter are currently clear.</p>
          </div>
        ) : (
          filteredAlerts.map(alert => {
            const styles = getAlertSeverityStyles(alert.severity, alert.status);
            return (
              <div
                key={alert.id}
                id={`alert-card-${alert.id}`}
                className={`p-4 sm:p-5 rounded-2xl border transition-all ${styles.cardBg} ${styles.borderColor} shadow-lg space-y-3`}
              >
                {/* Header Row */}
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2">
                  <div className="flex items-center gap-2.5">
                    <div className={`p-2 rounded-xl bg-slate-950 border border-slate-800 ${styles.iconColor}`}>
                      <AlertTriangle className="w-5 h-5" />
                    </div>
                    <div>
                      <div className="flex flex-wrap items-center gap-2">
                        <span className={`text-[10px] font-mono font-bold px-2.5 py-0.5 rounded-full border uppercase ${styles.badge}`}>
                          {alert.severity} ALERT
                        </span>
                        <span className="text-xs font-mono text-slate-400">
                          {alert.id}
                        </span>
                        <span className="text-xs font-mono text-cyan-400 px-2 py-0.5 rounded bg-slate-950 border border-slate-800">
                          Dept: {alert.department}
                        </span>
                      </div>
                      <h3 className="text-base font-bold text-white mt-0.5">
                        {alert.title}
                      </h3>
                    </div>
                  </div>

                  <div className="flex items-center gap-2 text-xs font-mono text-slate-400">
                    <Clock className="w-3.5 h-3.5 text-cyan-400" />
                    <span>{alert.timestamp}</span>
                  </div>
                </div>

                {/* Prompt Concrete Example Payload Info:
                    Depth: 0.65 m
                    Location: Detected Road Segment
                    Detected by: BUS-102
                */}
                <div className="grid grid-cols-1 sm:grid-cols-3 gap-2.5 text-xs font-mono bg-slate-950/80 p-3 rounded-xl border border-slate-800/80">
                  {/* Water Depth if applicable */}
                  <div>
                    <span className="text-[10px] text-slate-400 block uppercase">
                      {alert.depthMeters !== undefined ? 'Water Depth' : 'Hazard Class'}
                    </span>
                    <strong className="text-cyan-300 text-sm">
                      {alert.depthMeters !== undefined ? `Depth: ${alert.depthMeters.toFixed(2)} m (${alert.depthMeters * 100} cm)` : alert.type.replace('_', ' ').toUpperCase()}
                    </strong>
                  </div>

                  {/* Location */}
                  <div>
                    <span className="text-[10px] text-slate-400 block uppercase">Location</span>
                    <div className="flex items-center gap-1 text-slate-200">
                      <MapPin className="w-3 h-3 text-rose-400 shrink-0" />
                      <strong className="truncate">{alert.locationName}</strong>
                    </div>
                  </div>

                  {/* Detected by */}
                  <div>
                    <span className="text-[10px] text-slate-400 block uppercase">Detected by</span>
                    <div className="flex items-center gap-1 text-emerald-400">
                      <BusFront className="w-3 h-3 shrink-0" />
                      <strong>{alert.busId}</strong>
                    </div>
                  </div>
                </div>

                {/* Required Buttons from Prompt:
                    View on Map
                    Acknowledge
                    Mark Resolved
                */}
                <div className="flex flex-wrap items-center justify-between gap-2 pt-1 border-t border-slate-800/80">
                  <div className="text-xs font-mono text-slate-400">
                    Status:{' '}
                    <strong className={`capitalize ${
                      alert.status === 'resolved' 
                        ? 'text-emerald-400' 
                        : alert.status === 'acknowledged' 
                        ? 'text-amber-400' 
                        : 'text-rose-400'
                    }`}>
                      {alert.status}
                    </strong>
                  </div>

                  <div className="flex items-center gap-2">
                    {/* View on Map */}
                    <button
                      id={`alert-view-map-${alert.id}`}
                      onClick={() => viewHazardOnMap(alert.hazardId)}
                      className="px-3 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-cyan-300 text-xs font-mono font-medium border border-slate-700 transition-colors flex items-center gap-1.5"
                    >
                      <Eye className="w-3.5 h-3.5 text-cyan-400" />
                      <span>View on Map</span>
                    </button>

                    {/* Acknowledge */}
                    {alert.status === 'unacknowledged' && (
                      <button
                        id={`alert-ack-${alert.id}`}
                        onClick={() => acknowledgeAlert(alert.id)}
                        className="px-3 py-1.5 rounded-xl bg-amber-600/80 hover:bg-amber-600 text-white text-xs font-mono font-semibold transition-colors flex items-center gap-1.5"
                      >
                        <Check className="w-3.5 h-3.5" />
                        <span>Acknowledge</span>
                      </button>
                    )}

                    {/* Mark Resolved */}
                    {alert.status !== 'resolved' && (
                      <button
                        id={`alert-resolve-${alert.id}`}
                        onClick={() => resolveAlert(alert.id)}
                        className="px-3 py-1.5 rounded-xl bg-emerald-600 hover:bg-emerald-500 text-white text-xs font-mono font-bold transition-colors flex items-center gap-1.5"
                      >
                        <CheckCircle2 className="w-3.5 h-3.5" />
                        <span>Mark Resolved</span>
                      </button>
                    )}
                  </div>
                </div>
              </div>
            );
          })
        )}
      </div>
    </div>
  );
};
